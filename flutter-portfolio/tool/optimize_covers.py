"""Generate lightweight previews; keep original gallery media unchanged. Requires Pillow."""
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parent.parent
media = root / 'assets' / 'projects'
out = root / 'assets' / 'covers'
out.mkdir(exist_ok=True)
covers = {}
original_bytes = 0
for source in sorted(media.glob('*-00.*')):
    if source.suffix.lower() not in {'.png', '.jpg', '.jpeg', '.webp'}:
        continue
    key = source.stem.removesuffix('-00')
    image = ImageOps.exif_transpose(Image.open(source)).convert('RGB')
    image.thumbnail((1200, 800), Image.Resampling.LANCZOS)
    target = out / f'{key}.webp'
    image.save(target, 'WEBP', quality=82, method=6)
    covers[key] = f'assets/covers/{key}.webp'
    original_bytes += source.stat().st_size
portrait = ImageOps.exif_transpose(Image.open(media / 'profile.png')).convert('RGB')
portrait.thumbnail((120, 120), Image.Resampling.LANCZOS)
portrait.save(out / 'profile.webp', 'WEBP', quality=85, method=6)
lines = ['// Generated by tool/optimize_covers.py; full-resolution galleries remain unchanged.',
         'const projectCovers = <String, String>{']
lines += [f"  '{key}': '{value}'," for key, value in covers.items()]
lines += ['};', '']
(root / 'lib' / 'content' / 'project_covers.dart').write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(covers)} covers: {original_bytes:,} original bytes -> {sum((out / (key + ".webp")).stat().st_size for key in covers):,} preview bytes')
